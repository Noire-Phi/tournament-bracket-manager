package model;

public class Match {
    public enum Status { WAITING, READY, IN_PROGRESS, PLAYED }

    public final int id;
    public final int round;
    public Player a, b, winner;
    public Status status = Status.WAITING;
    public Match next;      // bracket link: where the winner goes
    public int nextSlot;    // 0 = player A slot, 1 = player B slot in `next`
    public boolean bracket; // true when generated by the bracket

    public Match(int id, int round) {
        this.id = id;
        this.round = round;
    }

    @Override
    public String toString() {
        return "#" + id + " R" + round + ": " + (a == null ? "TBD" : a.name) + " vs " + (b == null ? "TBD" : b.name);
    }
}
